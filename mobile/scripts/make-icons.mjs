// Generates every Android icon from the desktop artwork, so the hexagon has a
// single source: assets/icon-windows.svg. Re-run with `npm run icons` after
// that file changes.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Resvg } from '@resvg/resvg-js';

const here = path.dirname(fileURLToPath(import.meta.url));
const mobile = path.resolve(here, '..');
const source = path.resolve(mobile, '../assets/icon-windows.svg');
const res = path.join(mobile, 'android/app/src/main/res');
const svg = fs.readFileSync(source, 'utf8');

// --- Read the mark out of the desktop SVG rather than restating it.
const stops = [...svg.matchAll(/stop-color="(#[0-9a-f]{6})"/gi)].map((m) => m[1]);
const whiteGroup = /<g[^>]*stroke="(#[0-9a-f]{6})"[^>]*stroke-width="(\d+)"[^>]*>([\s\S]*?)<\/g>/i.exec(svg);
const accent = /<path d="([^"]+)"[^>]*stroke="(#[0-9a-f]{6})"/i.exec(svg.slice(whiteGroup.index + whiteGroup[0].length));
if (stops.length !== 2 || !whiteGroup || !accent) {
  throw new Error('icon-windows.svg no longer has the expected shape');
}
const [tileTop, tileBottom] = stops;
const [, white, strokeWidth, group] = whiteGroup;
const whitePaths = [...group.matchAll(/d="([^"]+)"/g)].map((m) => m[1]);
const [, accentPath, accentColor] = accent;

// --- Adaptive icon. The launcher masks a 108dp canvas and only guarantees a
// 66dp circle, so the mark is scaled to sit inside it at about the proportion
// it has on the desktop tile.
const VIEWPORT = 1024;
const MARK_SCALE = 0.86;
const vector = (body, extraNs = '') => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by mobile/scripts/make-icons.mjs from assets/icon-windows.svg. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"${extraNs}
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="${VIEWPORT}"
    android:viewportHeight="${VIEWPORT}">
${body}
</vector>
`;
const stroke = (d, color) => `        <path
            android:pathData="${d}"
            android:strokeColor="${color}"
            android:strokeWidth="${strokeWidth}"
            android:strokeLineCap="square" />`;
const mark = (colorFor) => `    <group
        android:pivotX="512"
        android:pivotY="512"
        android:scaleX="${MARK_SCALE}"
        android:scaleY="${MARK_SCALE}">
${whitePaths.map((d) => stroke(d, colorFor(white))).join('\n')}
${stroke(accentPath, colorFor(accentColor))}
    </group>`;

const write = (rel, text) => {
  const file = path.join(res, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
};

write('drawable/ic_launcher_foreground.xml', vector(mark((c) => c)));
// Themed icons recolour one layer, so every stroke is the same flat colour.
write('drawable/ic_launcher_monochrome.xml', vector(mark(() => '#FFFFFFFF')));
write('drawable/ic_launcher_background.xml', vector(`    <path android:pathData="M0,0h${VIEWPORT}v${VIEWPORT}h-${VIEWPORT}z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="0"
                android:startY="0"
                android:endX="0"
                android:endY="${VIEWPORT}"
                android:startColor="${tileTop}"
                android:endColor="${tileBottom}" />
        </aapt:attr>
    </path>`, '\n    xmlns:aapt="http://schemas.android.com/aapt"'));

const adaptive = `<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
`;
write('mipmap-anydpi-v26/ic_launcher.xml', adaptive);
write('mipmap-anydpi-v26/ic_launcher_round.xml', adaptive);

// Launch screen: the same mark on the tile's dark end, in place of the
// Capacitor logo the template ships.
write('drawable/splash.xml', `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by mobile/scripts/make-icons.mjs. -->
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:drawable="@color/sertum_splash" />
    <item android:drawable="@drawable/ic_launcher_foreground" android:gravity="center" />
</layer-list>
`);
write('values/sertum_colors.xml', `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by mobile/scripts/make-icons.mjs. -->
<resources>
    <color name="sertum_splash">${tileBottom}</color>
</resources>
`);

// --- Remove the template's art, which would otherwise win or linger.
for (const dir of fs.readdirSync(res)) {
  const full = path.join(res, dir);
  if (dir === 'drawable-v24') fs.rmSync(path.join(full, 'ic_launcher_foreground.xml'), { force: true });
  if (dir.startsWith('drawable')) fs.rmSync(path.join(full, 'splash.png'), { force: true });
  if (dir.startsWith('mipmap-') && dir !== 'mipmap-anydpi-v26') {
    fs.rmSync(path.join(full, 'ic_launcher_foreground.png'), { force: true });
  }
}
for (const dir of fs.readdirSync(res)) {
  const full = path.join(res, dir);
  if (fs.statSync(full).isDirectory() && fs.readdirSync(full).length === 0) fs.rmdirSync(full);
}

// --- Bitmaps: legacy launchers (API 24-25) and the Play listing.
const marks = whitePaths.map((d) => `<path d="${d}" fill="none" stroke="${white}" stroke-width="${strokeWidth}" stroke-linecap="square"/>`).join('')
  + `<path d="${accentPath}" fill="none" stroke="${accentColor}" stroke-width="${strokeWidth}" stroke-linecap="square"/>`;
const defs = `<defs><linearGradient id="t" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="${tileTop}"/><stop offset="1" stop-color="${tileBottom}"/></linearGradient></defs>`;
const circle = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024">${defs}<circle cx="512" cy="512" r="500" fill="url(#t)"/>${marks}</svg>`;
const square = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024">${defs}<rect width="1024" height="1024" fill="url(#t)"/>${marks}</svg>`;

const rasterise = (svgText, size, output) => {
  fs.mkdirSync(path.dirname(output), { recursive: true });
  const image = new Resvg(svgText, { fitTo: { mode: 'width', value: size } }).render();
  fs.writeFileSync(output, image.asPng());
};
for (const [bucket, size] of [['mdpi', 48], ['hdpi', 72], ['xhdpi', 96], ['xxhdpi', 144], ['xxxhdpi', 192]]) {
  rasterise(svg, size, path.join(res, `mipmap-${bucket}/ic_launcher.png`));
  rasterise(circle, size, path.join(res, `mipmap-${bucket}/ic_launcher_round.png`));
}
// Play requires 512x512, opaque, full-bleed; it applies its own mask.
rasterise(square, 512, path.join(mobile, 'assets/play-store-icon.png'));

console.log('Icons generated from', path.relative(mobile, source));
